def label(lang: str, group: str, value):
    """Localised label of a code value; the raw value when there is none."""
    if value is None:
        return None
    if group == "provenance" and isinstance(value, str) and value.startswith("table:"):
        word = "tabla" if lang == "es" else "table"
        return f"{word} ({value[len('table:'):]})"
    return ENUMS[lang].get(group, {}).get(value, value)
